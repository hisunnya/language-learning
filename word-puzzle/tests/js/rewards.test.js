'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
let now = 1700000000000;
const world = { Date: { now: () => now }, window: {} };
vm.createContext(world);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../../web/js/item-core.js'), 'utf8'), world);
const C = world.window.WPItemCore;
assert.equal(C.spellPoints({ solved: true }), 80);
const short = new C.Round('verb', 3);
assert.equal(short.limit, 36);
now += 36000;
assert.equal(short.left(), 0);
assert.equal(short.finish(0, false), 0);
const round = new C.Round('spell', 7);
assert.equal(round.limit, 140);
const bonuses = [];
for (let i = 0; i < 7; i++) bonuses.push(round.hit(80, true, i).points);
assert.equal(bonuses.join(','), '0,8,16,32,48,64,80');
assert.ok(round.secondsAdded <= 10);
assert.equal(round.hit(80, true, 6).points, 0);
const before = round.extra;
round.miss(8);
assert.equal(round.hit(80, true, 9).points, 0);
assert.equal(round.extra, before);
const paused = new C.Round('order', 1);
now += 5000;
paused.pause();
now += 120000;
assert.equal(paused.left(), 25);
paused.resume();
assert.equal(paused.left(), 25);
assert.equal(paused.elapsed(), 5);
const reduced = new C.Round('verb', 10, { score_factor: .2, time_factor: .4 });
assert.equal(reduced.limit, 48);
assert.equal(reduced.finish(100, false), 20);
assert.equal(reduced.finish(0, true), 0);
assert.equal(C.orderPoints({ arranged: true, recordingValid: true, bonus: 35 }), 85);
console.log('连击、动态时限、暂停、白卷和倍率测试全部通过');
