def smart_join(lines):
    """PDF 换行拼接：中文直连，拉丁词间补空格"""
    out = ""
    for ln in lines:
        if not out:
            out = ln
            continue
        if re.search(r"[A-Za-z0-9]$", out) and re.match(r"[A-Za-z0-9]", ln):
            out += " " + ln
        else:
            out += ln
    return out


def main():
    raw = json.load(open(f"{WORK}/merged_raw.json"))
    imgmap = json.load(open(f"{WORK}/image_map.json"))
    byid = {os.path.splitext(os.path.basename(q["f"]))[0]: v for q in raw.values() if q["f"] for v in [imgmap.get(os.path.splitext(os.path.basename(q["f"]))[0])]}

    questions = []
    for q in raw.values():
        stem = smart_join(q["q"].split("\n"))
        opts = [smart_join(o.split("\n")) for o in q["opts"]]
        key = os.path.splitext(os.path.basename(q["f"]))[0] if q["f"] else ""
        questions.append({
            "id": q["i"],
            "no": q["j"],
            "cls": [c for c in ("A", "B", "C") if c in q["cls"]],
            "p": q["p"],
            "t": "s" if len(q["t"]) == 1 else "m",
            "q": stem,
            "o": opts,
            "a": q["t"],
            "img": byid.get(key) if q["f"] else None,
        })
    questions.sort(key=lambda x: (x["p"], x["id"]))

    # 源 PDF 里 249 道题的 [J] 题号是占位符 "LX"，另有少量重复题号，
    # 因此显示用编号取 [J]，若不唯一则退回唯一可靠的 [I] 编号。
    from collections import Counter
    jc = Counter(q["no"] for q in questions)
    for q in questions:
        q["uid"] = q["no"] if jc[q["no"]] == 1 else q["id"]
        if jc[q["no"]] > 1:
            q["uid"] = q["id"]
    n_fallback = sum(1 for q in questions if q["uid"] == q["id"])
    print(f"显示编号：{len(questions) - n_fallback} 道用原题号，{n_fallback} 道回退到 [I] 编号")

    tree = {}
    for q in questions:
        parts = q["p"].split(".")
        g = parts[0]
        s = ".".join(parts[:2])
        p = q["p"]
        tree.setdefault(g, {}).setdefault(s, {}).setdefault(p, 0)
        tree[g][s][p] += 1

    data = {
        "meta": {
            "title": "业余无线电台操作技术能力验证 模拟考试系统",
            "bank": "《业余无线电台操作技术能力验证题库（2025 年版）》",
            "note": "题量与官方一致：A 683 / B 1143 / C 1282",
            "generated": "2026-10-23",
        },
        "groups": GROUPS,
        "sections": SECTIONS,
        "points": POINTS,
        "tree": tree,
        "questions": questions,
    }
    os.makedirs(f"{OUT_DIR}/data", exist_ok=True)
    with open(f"{OUT_DIR}/data/bank.json", "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
    size = os.path.getsize(f"{OUT_DIR}/data/bank.json")
    print(f"题目 {len(questions)} 题，知识点 {len(POINTS)} 个，bank.json = {size/1024:.0f} KB")
    miss = [q["id"] for q in questions if q["cls"] == []]
    print("无类别归属:", len(miss))


if __name__ == "__main__":
    main()
